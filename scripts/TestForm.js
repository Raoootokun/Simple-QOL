function showForm(player) {
    const LIST = [ `§c■`, `§a■`, `§b■` ];
    
    const label = Observable.create('', { clientWritable: true });

    const form = CustomForm.create(player, 'MINI SLOT');
    form.closeButton();
    form.label(`Space is Stop!`);
    for(const T of AAA) {
        form.label(`${T.join(``)}`);
    }
    form.show();

    const systemNum = system.runInterval(() => {
        //フォームを閉じた場合
        if(!form.isShowing())return system.clearRun(systemNum);

        label.setData(`${LIST[random(0, 2, true)]}`);
    });

}

